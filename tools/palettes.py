#!/usr/bin/env python3
"""Generate Sift's copy of the house palettes from ProjectForge's palettes.toml.

    python3 tools/palettes.py [path/to/palettes.toml]
    pf palette apply . --done      # then record that the copy is current

Writes three files, all generated — edit palettes.toml, never these:

  app/src/main/res/values/palettes.xml        one style per palette (the light form
                                              for the palettes that follow light/dark)
  app/src/main/res/values-night/palettes.xml  the dark form of those palettes
  app/src/main/java/com/sift/explorer/util/Palettes.java   the picker's list

Roles map onto Material 3 exactly as the Compose apps do it (TextX/ThereminX
`keyx()`), so a palette looks the same in Sift as in every other house app.
"""
import os
import sys
import tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_SRC = "/media/veracrypt1/Rust/ProjectForge/palettes.toml"
RES = os.path.join(ROOT, "app/src/main/res")
JAVA = os.path.join(ROOT, "app/src/main/java/com/sift/explorer/util/Palettes.java")

HEADER = ("<!-- GENERATED by tools/palettes.py from ProjectForge palettes.toml. Do not edit:\n"
          "     change the house palettes, run the script, then record it with pf palette apply. -->\n")


def key(name):
    return "".join(w[:1].upper() + w[1:] for w in name.replace("-", " ").split())


def attr(role):
    special = {
        "background": "android:colorBackground",
        "inverseSurface": "colorSurfaceInverse",
        "inverseOnSurface": "colorOnSurfaceInverse",
        "inversePrimary": "colorPrimaryInverse",
    }
    return special.get(role, "color" + role[0].upper() + role[1:])


def luminance(hex_):
    def ch(v):
        v /= 255
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = (int(hex_[i:i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b)


def scheme(r):
    """The house role → Material role mapping (keyx() in the Compose apps)."""
    return {
        "primary": r["accent"], "onPrimary": r["on_accent"],
        "primaryContainer": r["pressed"], "onPrimaryContainer": r["text"],
        "secondary": r["accent_secondary"], "onSecondary": r["background"],
        "secondaryContainer": r["pressed"], "onSecondaryContainer": r["text"],
        "tertiary": r["highlight"], "onTertiary": r["background"],
        "tertiaryContainer": r["pressed"], "onTertiaryContainer": r["text"],
        "background": r["background"], "onBackground": r["text"],
        "surface": r["background"], "onSurface": r["text"],
        "surfaceVariant": r["surface"], "onSurfaceVariant": r["text_secondary"],
        "surfaceContainerLowest": r["background"], "surfaceContainerLow": r["bars"],
        "surfaceContainer": r["bars"], "surfaceContainerHigh": r["raised"],
        "surfaceContainerHighest": r["surface"], "surfaceBright": r["raised"],
        "surfaceDim": r["background"],
        "outline": r["border"], "outlineVariant": r["border"],
        "inverseSurface": r["text"], "inverseOnSurface": r["background"],
        "inversePrimary": r["pressed"],
    }


def style(name, parent, colors, background, top_bar, mono):
    out = [f'    <style name="{name}" parent="{parent}">']
    for role, value in colors.items():
        out.append(f'        <item name="{attr(role)}">{value}</item>')
    out.append(f'        <item name="colorTopBar">{top_bar}</item>')
    out.append('        <item name="android:statusBarColor">@android:color/transparent</item>')
    out.append('        <item name="android:navigationBarColor">@android:color/transparent</item>')
    out.append(f'        <item name="android:windowBackground">{background}</item>')
    if mono:
        out.append('        <item name="fontFamily">monospace</item>')
        out.append('        <item name="android:fontFamily">monospace</item>')
    out.append('    </style>')
    return "\n".join(out)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SRC
    with open(src, "rb") as f:
        palettes = tomllib.load(f)["palette"]

    day, night, java = [], [], []
    for p in palettes:
        name, k = p["name"], key(p["name"])
        sname = f"Theme.Sift.Palette.{k}"
        mono = bool(p.get("mono"))
        label = p.get("label", name)
        if p.get("dynamic"):
            # The platform supplies the colours (DynamicColors); stock Material 3 below Android 12.
            day.append(style(sname, "Theme.Material3.DayNight.NoActionBar", {},
                             "?android:attr/colorBackground", "?attr/colorSurfaceContainer", mono))
            java.append((name, label, k, True, mono, False, None, None))
            continue
        roles = p["roles"]
        dark_colors = scheme(roles)
        dark_colors.update(p.get("overrides", {}))
        if "light" in p:
            # Follows light/dark. Top bar keeps Sift's own white / black strip.
            light = dict(p["light"])
            day.append(style(sname, "Theme.Material3.Light.NoActionBar", light,
                             light.get("background", "#FFFFFF"), "#FFFFFF", mono))
            night.append(style(sname, "Theme.Material3.Dark.NoActionBar", dark_colors,
                               roles["background"], "#000000", mono))
            java.append((name, label, k, True, mono, False, roles["accent"], roles["background"]))
        else:
            is_light = luminance(roles["background"]) > 0.5
            parent = "Theme.Material3.Light.NoActionBar" if is_light else "Theme.Material3.Dark.NoActionBar"
            day.append(style(sname, parent, dark_colors, roles["background"], roles["bars"], mono))
            java.append((name, label, k, False, mono, is_light, roles["accent"], roles["background"]))

    def write_xml(path, styles):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write('<?xml version="1.0" encoding="utf-8"?>\n' + HEADER + "<resources>\n")
            f.write("\n\n".join(styles) + "\n</resources>\n")

    write_xml(os.path.join(RES, "values/palettes.xml"), day)
    write_xml(os.path.join(RES, "values-night/palettes.xml"), night)

    def jstr(s):
        return "null" if s is None else '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

    def jcolor(s):
        return "0" if s is None else "0xFF" + s[1:].upper()

    rows = ",\n".join(
        f"            new Palette({jstr(n)}, {jstr(l)}, R.style.Theme_Sift_Palette_{k}, "
        f"{str(f).lower()}, {str(m).lower()}, {str(li).lower()}, {jcolor(a)}, {jcolor(b)})"
        for n, l, k, f, m, li, a, b in java)
    with open(JAVA, "w") as f:
        f.write(f"""package com.sift.explorer.util;

import com.sift.explorer.R;

/**
 * The house palettes, in the picker's order. GENERATED by tools/palettes.py from ProjectForge
 * palettes.toml — do not edit; change the house palettes and run the script.
 */
public final class Palettes {{

    private Palettes() {{}}

    public static final class Palette {{
        /** Saved by this name, so adding palettes never shifts a saved choice. */
        public final String name;
        public final String label;
        public final int style;
        /** Material You, Ocean and Terminal follow the dark-mode switch; the rest are one look. */
        public final boolean followsMode;
        public final boolean mono;
        /** For a fixed palette: whether that one look is a light one. */
        public final boolean light;
        /** Swatch colours for the picker; 0 for Material You (the wallpaper decides). */
        public final int accent, background;

        Palette(String name, String label, int style, boolean followsMode, boolean mono,
                boolean light, int accent, int background) {{
            this.name = name; this.label = label; this.style = style;
            this.followsMode = followsMode; this.mono = mono; this.light = light;
            this.accent = accent; this.background = background;
        }}

        public boolean isDynamic() {{ return accent == 0; }}
    }}

    public static final String MATERIAL_YOU = "Material You";

    public static final Palette[] ALL = {{
{rows}
    }};

    /** Case, spaces and dashes do not matter ("white-glow"), as with `pf palette show`. */
    public static Palette byName(String name) {{
        if (name == null) return null;
        String want = norm(name);
        for (Palette p : ALL) if (norm(p.name).equals(want)) return p;
        return null;
    }}

    private static String norm(String s) {{
        return s.toLowerCase(java.util.Locale.ROOT).replace(" ", "").replace("-", "").replace("_", "");
    }}
}}
""")
    print(f"{len(palettes)} palettes -> palettes.xml (+night) and Palettes.java")


if __name__ == "__main__":
    main()
